"""
Обработчик для кнопки "Как это работает?".
"""
from aiogram import Router, types, F
from aiogram.fsm.context import FSMContext

from app.bot.keyboards import get_main_menu_keyboard
from app.utils.logging import logger

router = Router()


@router.message(F.text == "📖 Как это работает?")
async def show_how_it_works(message: types.Message, state: FSMContext):
    """Показывает информацию о работе бота."""
    await state.clear()

    text = (
        "🧠 <b>Как это работает</b>\n\n"
        "Сома помогает лучше замечать своё состояние и возможные связи между телом, "
        "эмоциями, мыслями, сном, питанием, нагрузкой и событиями жизни.\n\n"

        "📝 <b>Описать состояние</b>\n"
        "Ты рассказываешь, что замечаешь сейчас. Сома задаёт только необходимые вопросы "
        "и помогает посмотреть на ситуацию с разных сторон.\n\n"

        "📔 <b>Дневник и История</b>\n"
        "Твои наблюдения сохраняются, чтобы к ним можно было вернуться позже.\n\n"

        "📊 <b>Динамика</b>\n"
        "Можно посмотреть, что повторялось, что изменилось и на что стоит обратить внимание.\n\n"

        "🔔 <b>Напоминания</b>\n"
        "Можно включить напоминание, чтобы не забывать описывать своё состояние.\n\n"

        "⭐ <b>PRO</b>\n"
        "Первые 3 дня доступны бесплатно. После этого можно продолжить общение с Сомой "
        "без ограничений в PRO.\n\n"

        "⚠️ <b>Важно</b>\n"
        "Сома не ставит диагнозы и не заменяет врача. Её наблюдения не являются "
        "медицинскими заключениями.\n\n"

        "🌿 <b>Начать</b>\n"
        "Нажми «Описать состояние» и расскажи, что происходит сейчас."
    )

    await message.answer(
        text,
        reply_markup=get_main_menu_keyboard(),
        parse_mode="HTML",
    )

    logger.info(f"User viewed 'How it works': {message.from_user.id}")