"""
Сервис безопасности. Перехватывает опасные сообщения ДО отправки в AI.
"""
import re
from typing import Tuple
from enum import Enum


class SafetyLevel(str, Enum):
    OK = "ok"
    WARNING = "warning"
    CRITICAL = "critical"


class SafetyResult:
    def __init__(self, level: SafetyLevel, warning: str = None):
        self.level = level
        self.warning = warning


class SafetyService:
    """Проверка входящих сообщений на опасный контент."""

    # ==================== КРИТИЧЕСКИЕ ТРИГГЕРЫ (УГРОЗА ЖИЗНИ) ====================
    CRITICAL_KEYWORDS = [
        # Суицид / самоповреждение
        "покончить с собой", "убить себя", "суицид", "не хочу жить",
        "порезать вены", "выброситься", "спрыгнуть", "отравиться",
        # Угроза другим
        "убить", "зарезать", "взорвать", "навредить",
        # Острые физические симптомы
        "инфаркт", "инсульт", "не могу дышать", "задыхаюсь",
        "сильная боль в груди", "кровотечение", "потерял сознание",
        "парализовало", "отнялась рука", "отнялась нога"
    ]

    # ==================== ПРЕДУПРЕЖДЕНИЯ (ТРЕБУЕТСЯ ВРАЧ) ====================
    WARNING_KEYWORDS = [
        "болит сердце", "болит грудь", "высокое давление",
        "температура 39", "температура 40", "не прохожу уже неделю",
        "сильная слабость", "теряю вес", "кровь в стуле"
    ]

    def check_input(self, text: str) -> SafetyResult:
        """Проверяет текст на наличие опасных триггеров."""
        if not text:
            return SafetyResult(SafetyLevel.OK)

        text_lower = text.lower()

        # Проверка на критические триггеры
        for keyword in self.CRITICAL_KEYWORDS:
            if keyword in text_lower:
                return SafetyResult(
                    level=SafetyLevel.CRITICAL,
                    warning=(
                        "🚨 <b>Важно: это серьёзно.</b>\n\n"
                        "Я слышу, что тебе очень тяжело, и то, что ты описываешь, требует реальной поддержки.\n\n"
                        "Пожалуйста, не оставайся с этим один. Если есть угроза жизни или здоровью — "
                        "немедленно позвони в экстренную службу по месту нахождения (например, 112 или 103 в РФ) "
                        "или обратись в ближайшее отделение неотложной помощи.\n\n"
                        "Если можешь — напиши или позвони близкому человеку, которому доверяешь, и попроси побыть с тобой.\n\n"
                        "Ты важен. Твоя безопасность сейчас — самое главное."
                    )
                )

        # Проверка на предупреждения
        for keyword in self.WARNING_KEYWORDS:
            if keyword in text_lower:
                return SafetyResult(
                    level=SafetyLevel.WARNING,
                    warning=(
                        "⚠️ <b>Пожалуйста, будь внимателен к своему телу.</b>\n\n"
                        "Симптомы, которые ты описываешь, могут требовать медицинской проверки.\n"
                        "Я не врач и не могу оценить физическое состояние. Пожалуйста, "
                        "обратись к врачу или в неотложную помощь, чтобы исключить серьёзные причины.\n\n"
                        "Я поддержу тебя, когда ты будешь готов поговорить."
                    )
                )

        return SafetyResult(SafetyLevel.OK)


# Глобальный экземпляр
safety_service = SafetyService()