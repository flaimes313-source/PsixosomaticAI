"""
Тексты сообщений для опросов.
"""
from app.utils.survey_affirmations import get_next_affirmation


def get_morning_survey_text() -> str:
    """Возвращает текст для утреннего опроса."""
    affirmation = get_next_affirmation()
    return (
        f"🌅 <b>Доброе утро!</b>\n\n"
        f"✨ <i>«{affirmation}»</i>\n\n"
        "Давай начнём день с небольшого наблюдения за собой.\n"
        "Ответь на несколько вопросов — это поможет лучше понять своё состояние.\n\n"
        "1️⃣ <b>Как ты проснулся?</b>\n"
        "Напиши одним словом: бодро, тяжело, тревожно или спокойно."
    )


def get_day_survey_text() -> str:
    """Возвращает текст для дневного опроса."""
    return (
        "☀️ <b>Добрый день!</b>\n\n"
        "Давай проверим, как проходит твой день.\n"
        "Ответь на несколько коротких вопросов.\n\n"
        "1️⃣ <b>Как ты сейчас себя чувствуешь?</b>\n"
        "Напиши одним словом: хорошо, нормально, тревожно или устало."
    )


